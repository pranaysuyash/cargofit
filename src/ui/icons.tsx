/** Helper to render product icon from product id */
export const ProductIcon: React.FC<{ productId: string; size?: number | string; className?: string }> = ({
  productId,
  size = 20,
  className,
}) => {
  switch (productId) {
    case 'command-center-portal':
      return <IconCommand size={size} className={className} />;
    case 'product-01-cargo-fit':
      return <IconPackage size={size} className={className} />;
    case 'product-02-freight-pricing':
      return <IconDollar size={size} className={className} />;
    case 'product-03-hos-planner':
      return <IconClock size={size} className={className} />;
    case 'product-04-asset-studio':
      return <IconTruck size={size} className={className} />;
    case 'product-05-fleet-telematics':
      return <IconRadio size={size} className={className} />;
    default:
      return <IconTruck size={size} className={className} />;
  }
};
